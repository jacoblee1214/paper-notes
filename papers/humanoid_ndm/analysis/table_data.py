def _row(s):
    """'a±b' 또는 'a' 12개를 (mean, sd) 튜플 12개로"""
    out = []
    for tok in s.split():
        if "±" in tok:
            m, sd = tok.split("±")
            out.append((float(m), float(sd)))
        else:
            out.append((float(tok), None))
    assert len(out) == 12, s
    return out


